def converter_data(data_dd_mm_yyyy):
    """Converte DD/MM/YYYY para YYYY-MM-DD"""
    try:
        d, m, y = data_dd_mm_yyyy.split('/')
        return f"{y}-{m.zfill(2)}-{d.zfill(2)}"
    except:
        return None

def gerar_updates():
    """Gera comandos UPDATE para cada registro"""
    updates = []
    erros = []
    
    for linha in dados_corretos.strip().split('\n'):
        try:
            cpf, codigo, data_br = linha.strip().split(';')
            cpf_limpo = cpf.replace('.', '').replace('-', '').replace('/', '')
            data_iso = converter_data(data_br)
            
            if data_iso:
                update = f"""UPDATE qualificacoes_historico 
SET data_conclusao = '{data_iso}',
    data_vencimento = date('{data_iso}', '+' || COALESCE((SELECT validade FROM qualificacoes_tipos WHERE codigo = '{codigo}'), 0) || ' months'),
    updated_at = datetime('now')
WHERE REPLACE(REPLACE(REPLACE(funcionario_cpf, '.', ''), '-', ''), '/', '') = '{cpf_limpo}' 
  AND UPPER(TRIM(qualificacao_codigo)) = UPPER(TRIM('{codigo}'))
  AND deleted_at IS NULL;"""
                updates.append(update)
            else:
                erros.append(f"Data inválida: {linha}")
        except Exception as e:
            erros.append(f"Erro em linha: {linha} - {str(e)}")
    
    return updates, erros

def executar_batch(updates, batch_size=50):
    """Executa UPDATEs em batches"""
    total = len(updates)
    sucesso = 0
    falhas = 0
    
    print(f"🚀 Iniciando correção de {total} registros...")
    print(f"📦 Batch size: {batch_size}\n")
    
    for i in range(0, total, batch_size):
        batch = updates[i:i+batch_size]
        sql = '\n'.join(batch)
        
        try:
            # Salva batch temporário
            with open('/tmp/batch_update.sql', 'w') as f:
                f.write(sql)
            
            # Executa via wrangler
            result = subprocess.run(
                ['wrangler', 'd1', 'execute', 'airtrust-db', '--remote', '--file', '/tmp/batch_update.sql'],
                capture_output=True,
                text=True,
                timeout=60
            )
            
            if result.returncode == 0:
                sucesso += len(batch)
                print(f"✅ Batch {i//batch_size + 1}: {len(batch)} registros atualizados ({sucesso}/{total})")
            else:
                falhas += len(batch)
                print(f"❌ Batch {i//batch_size + 1} falhou: {result.stderr}")
                
        except subprocess.TimeoutExpired:
            falhas += len(batch)
            print(f"⏱️  Batch {i//batch_size + 1} timeout")
        except Exception as e:
            falhas += len(batch)
            print(f"❌ Erro batch {i//batch_size + 1}: {str(e)}")
    
    print(f"\n📊 Resultado final:")
    print(f"   ✅ Sucesso: {sucesso}")
    print(f"   ❌ Falhas: {falhas}")
    print(f"   📈 Taxa: {(sucesso/total*100):.1f}%")
    
    return sucesso, falhas

