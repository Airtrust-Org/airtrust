"""Review-only Player3 terminal intent in SQLite memory, no remote writes.

Rehearses the actual 0552/0553 + 0554/0555 candidate chain and asserts
that a multi-stage authority cannot be substituted by Native single-attempt
evidence. A certificate is NOT generated by these database tests.
"""
import json
import sqlite3
import unittest

from scripts.__tests__.test_native_completion_intent_rehearsal import (
    setup, complete, HASH,
)

NONCE = '9' * 64
COLUMNS = (
    "nonce,empresa_id,curso_id,matricula_id,ciclo_id,funcionario_id,"
    "actor_user_id,vinculo_id,edicao_id,politica_id,edition_sha256,"
    "source_sha256,bank_sha256,policy_sha256,required_lesson_ids_json,"
    "official_stage_receipts_json,event_count,distinct_lesson_count,"
    "official_stage_count,gerar_qualificacao,qualificacao_tipo_id,"
    "qualificacao_categoria_id"
)


def seeded():
    db,m,cy,b,_=setup()
    db.execute("""INSERT INTO lms_player3_politicas (
      edicao_id,empresa_id,curso_id,source_sha256,policy_sha256,bank_sha256
    ) VALUES(1,6,10,?,?,?)""",(HASH,HASH,HASH))
    db.execute("""UPDATE lms_player3_politicas SET estado='APPROVED',
      approved_at=datetime('now'),approver_user_id=900 WHERE id=1""")
    attempt=db.execute("""INSERT INTO lms_player3_tentativas_modulares(
      vinculo_id,politica_id,etapa_id,tentativa_numero,event_id,answers_json,
      answers_sha256,score_pct,passed
    ) VALUES(?,1,'stage-1',1,'evt1','[]',?,85,1)""",(b,HASH)).lastrowid
    db.commit()
    return db,m,cy,b,attempt


def insert(db,m,cy,b,attempt,*,actor=900,tenant=6,course=10,employee=69,
           stage_hash=HASH,lessons=None,stages=None,nonce=NONCE,
           distinct=1,events=1):
    lesson_ids=['lesson-1'] if lessons is None else lessons
    receipts=([{'stageId':'stage-1','attemptId':attempt,'attemptNumber':1,
                'answersHash':stage_hash,'scorePct':85}] if stages is None else stages)
    args=(nonce,tenant,course,m,cy,employee,actor,b,1,1,HASH,HASH,HASH,HASH,
          json.dumps(lesson_ids),json.dumps(receipts),events,distinct,
          len(receipts),0,None,None)
    assert len(args)==22
    db.execute(f"INSERT INTO lms_player3_completion_intents ({COLUMNS})"
               f" VALUES ({','.join('?' for _ in args)})",args)


class Player3TerminalIntentReviewTests(unittest.TestCase):
    def test_verified_player3_intent_unlocks_both_rows_then_disappears(self):
        db,m,cy,b,attempt=seeded()
        try:
            with db:
                db.execute('BEGIN IMMEDIATE')
                insert(db,m,cy,b,attempt)
                complete(db,m,cy)
                db.execute("DELETE FROM lms_player3_completion_intents WHERE nonce=?",(NONCE,))
            self.assertEqual(db.execute("SELECT status FROM lms_matriculas WHERE id=?",(m,)).fetchone()[0],"CONCLUIDO")
            self.assertEqual(db.execute("SELECT status FROM lms_matricula_ciclos WHERE id=?",(cy,)).fetchone()[0],"CONCLUIDO")
            self.assertEqual(db.execute("SELECT COUNT(*) FROM lms_player3_completion_intents").fetchone()[0],0)
            self.assertEqual(db.execute("PRAGMA foreign_key_check").fetchall(),[])
        finally:db.close()

    def test_no_intent_cannot_complete_marked_scorm(self):
        db,m,cy,b,attempt=seeded()
        try:
            with self.assertRaisesRegex(sqlite3.IntegrityError,"NATIVE_CATALOG_COMPLETION_NOT_GOVERNED"):
                complete(db,m,cy)
        finally:db.close()

    def test_forged_actor_tenant_course_employee_or_receipt_denied(self):
        for patch in ({'actor':901},{'tenant':7},{'course':11},
                      {'employee':70},{'stage_hash':'b'*64}):
            db,m,cy,b,attempt=seeded()
            try:
                with self.assertRaisesRegex(sqlite3.IntegrityError,"PLAYER3_TERMINAL_INTENT_SCOPE_DENIED"):
                    insert(db,m,cy,b,attempt,**patch)
            finally:db.close()

    def test_missing_content_or_duplicate_lessons_denied(self):
        db,m,cy,b,attempt=seeded()
        try:
            with self.assertRaisesRegex(sqlite3.IntegrityError,"PLAYER3_TERMINAL_INTENT_SCOPE_DENIED"):
                insert(db,m,cy,b,attempt,lessons=['invented'])
            db.execute("""INSERT INTO lms_native_eventos(
              vinculo_id,event_id,sequencia,unidade_id,payload_sha256
            ) VALUES(?,'visit2',2,'lesson-2',?)""",(b,HASH))
            with self.assertRaisesRegex(sqlite3.IntegrityError,"PLAYER3_TERMINAL_INTENT_SCOPE_DENIED"):
                insert(db,m,cy,b,attempt,lessons=['lesson-1','lesson-1'],distinct=2,events=2)
        finally:db.close()

    def test_orphan_intent_forces_full_transaction_rollback(self):
        db,m,cy,b,attempt=seeded()
        try:
            with self.assertRaises(sqlite3.IntegrityError):
                with db:
                    db.execute('BEGIN IMMEDIATE')
                    insert(db,m,cy,b,attempt)
                    complete(db,m,cy)
                    # Omit DELETE -> deferred sentinel FK must abort COMMIT.
            self.assertEqual(db.execute("SELECT status FROM lms_matriculas WHERE id=?",(m,)).fetchone()[0],"EM_ANDAMENTO")
            self.assertEqual(db.execute("SELECT status FROM lms_matricula_ciclos WHERE id=?",(cy,)).fetchone()[0],"EM_ANDAMENTO")
            self.assertEqual(db.execute("SELECT COUNT(*) FROM lms_player3_completion_intents").fetchone()[0],0)
        finally:db.close()

    def test_intent_is_immutable_until_consumed(self):
        db,m,cy,b,attempt=seeded()
        try:
            with db:
                db.execute('BEGIN IMMEDIATE')
                insert(db,m,cy,b,attempt)
                with self.assertRaisesRegex(sqlite3.IntegrityError,"PLAYER3_TERMINAL_INTENT_IMMUTABLE"):
                    db.execute("UPDATE lms_player3_completion_intents SET actor_user_id=901")
                db.execute("DELETE FROM lms_player3_completion_intents WHERE nonce=?",(NONCE,))
        finally:db.close()


if __name__ == "__main__":
    unittest.main()
